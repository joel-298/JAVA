// -> OOPS Definition : Way of writing an organized code using classes and objects 



// -> It has 4 pillars : 

//     -> Inheritance : Idea:    One class can inherit properties and behavior from another, avoiding repetition.
//                      Example: A car is a type of vehicle. Instead of creating everything from scratch, we reuse common features (wheels, engine).

//     -> Abstraction : Idea: Show only important things, hiding unnecessary details.
//                      Example: When you drive a car, you just press the accelerator. You don’t need to know how the engine works internally.

//     -> Encapsulation : Idea:    Keep important data private and allow access through controlled methods.
//                        Example: A mobile phone has internal components (battery, processor) that you cannot access directly. 
//                                 You use buttons and the touchscreen (methods) to interact with it.

//     -> Polymorphism : Idea: One function can behave differently in different situations.
//                       Example: A TV remote has a single power button, but it works for different TVs (Sony, Samsung, LG).